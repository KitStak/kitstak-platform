/** 5.2 Jobs and plans. */
import { boolean, date, integer, jsonb, numeric, text, uuid } from 'drizzle-orm/pg-core';
import { base, cents, hrs, orgId, pace, price, pulseSchema, qty, stream, tstz } from './_shared';

export interface UsualCrewLine {
  readonly laborClassId: string;
  readonly headcount: number;
}

export const jobs = pulseSchema.table('jobs', {
  ...base(),
  number: text('number').notNull(),
  name: text('name').notNull(),
  clientId: uuid('client_id').notNull(),
  jobTypeId: uuid('job_type_id').notNull(),
  siteId: uuid('site_id').notNull(),
  kind: text('kind').notNull().default('one_time'),
  status: text('status').notNull().default('planned'),
  pricingModel: text('pricing_model').notNull().default('per_unit'),
  unitLabel: text('unit_label').notNull().default('units'),
  plannedUnits: qty('planned_units').notNull().default('0'),
  unitPrice: price('unit_price'),
  fixedPriceCents: cents('fixed_price_cents'),
  billRateCents: integer('bill_rate_cents'),
  materialMethod: text('material_method').notNull().default('standard'),
  materialCostPerUnit: price('material_cost_per_unit').notNull().default('0'),
  partsOwner: text('parts_owner'),
  defaultLaborClassId: uuid('default_labor_class_id'),
  usualCrew: jsonb('usual_crew').$type<UsualCrewLine[]>().notNull().default([]),
  standardUph: pace('standard_uph'),
  targetMarginBp: integer('target_margin_bp'),
  startDate: date('start_date'),
  dueDate: date('due_date'),
  completedDate: date('completed_date'),
  activatedAt: tstz('activated_at'),
  poNumber: text('po_number'),
  ownerId: uuid('owner_id'),
  description: text('description'),
  kitSku: text('kit_sku'),
  kitName: text('kit_name'),
  wmsShortage: boolean('wms_shortage').notNull().default(false),
  /** True while a `pm_program` link points at this job. The program sync keeps it (0016). */
  programJob: boolean('program_job').notNull().default(false),
  pinnedNote: text('pinned_note'),
  archivedAt: tstz('archived_at'),
  ...stream(),
});

export const jobPrices = pulseSchema.table('job_prices', {
  ...base(),
  jobId: uuid('job_id').notNull(),
  effectiveFrom: date('effective_from').notNull(),
  unitPrice: price('unit_price'),
  billRateCents: integer('bill_rate_cents'),
  materialCostPerUnit: price('material_cost_per_unit').notNull().default('0'),
  note: text('note'),
  createdBy: uuid('created_by'),
});

export const jobPlans = pulseSchema.table('job_plans', {
  ...base(),
  jobId: uuid('job_id').notNull(),
  plan: text('plan').notNull(),
  units: qty('units').notNull().default('0'),
  revenueCents: cents('revenue_cents').notNull().default(BigInt(0)),
  laborHours: hrs('labor_hours').notNull().default('0'),
  laborCents: cents('labor_cents').notNull().default(BigInt(0)),
  setupHours: hrs('setup_hours').notNull().default('0'),
  setupCents: cents('setup_cents').notNull().default(BigInt(0)),
  materialCents: cents('material_cents').notNull().default(BigInt(0)),
  otherCents: cents('other_cents').notNull().default(BigInt(0)),
  sharedCents: cents('shared_cents').notNull().default(BigInt(0)),
  sharedAuto: boolean('shared_auto').notNull().default(true),
  version: integer('version').notNull().default(1),
  origin: text('origin').notNull().default('typed'),
  originRef: text('origin_ref'),
  note: text('note'),
  lockedAt: tstz('locked_at'),
  updatedBy: uuid('updated_by'),
});

export const jobPlanLines = pulseSchema.table('job_plan_lines', {
  ...base(),
  planId: uuid('plan_id').notNull(),
  jobId: uuid('job_id').notNull(),
  position: integer('position').notNull().default(0),
  category: text('category').notNull(),
  description: text('description'),
  quantity: qty('quantity'),
  unit: text('unit'),
  unitAmount: price('unit_amount'),
  amountCents: cents('amount_cents').notNull(),
  flex: boolean('flex'),
  laborClassId: uuid('labor_class_id'),
  vasServiceId: uuid('vas_service_id'),
  itemId: uuid('item_id'),
});

export const jobLinks = pulseSchema.table('job_links', {
  ...base(),
  jobId: uuid('job_id').notNull(),
  targetType: text('target_type').notNull(),
  targetId: text('target_id').notNull(),
  importsTime: boolean('imports_time').notNull().default(false),
  cachedTitle: text('cached_title'),
  cachedStatus: text('cached_status'),
  cachedUrl: text('cached_url'),
  cachedAt: tstz('cached_at'),
  meta: jsonb('meta').$type<Record<string, unknown>>().notNull().default({}),
  createdBy: uuid('created_by'),
});

export const jobStats = pulseSchema.table('job_stats', {
  jobId: uuid('job_id').primaryKey(),
  orgId: orgId(),
  unitsGood: numeric('units_good', { precision: 16, scale: 3 }).notNull().default('0'),
  unitsScrap: numeric('units_scrap', { precision: 16, scale: 3 }).notNull().default('0'),
  unitsRework: numeric('units_rework', { precision: 16, scale: 3 }).notNull().default('0'),
  hours: numeric('hours', { precision: 12, scale: 2 }).notNull().default('0'),
  overtimeHours: numeric('overtime_hours', { precision: 12, scale: 2 }).notNull().default('0'),
  setupHours: numeric('setup_hours', { precision: 12, scale: 2 }).notNull().default('0'),
  paceHours: numeric('pace_hours', { precision: 12, scale: 2 }).notNull().default('0'),
  evidenceDays: integer('evidence_days').notNull().default(0),
  revenueCents: cents('revenue_cents').notNull().default(BigInt(0)),
  baseRevenueCents: cents('base_revenue_cents').notNull().default(BigInt(0)),
  vasRevenueCents: cents('vas_revenue_cents').notNull().default(BigInt(0)),
  otherRevenueCents: cents('other_revenue_cents').notNull().default(BigInt(0)),
  billedCents: cents('billed_cents').notNull().default(BigInt(0)),
  laborCents: cents('labor_cents').notNull().default(BigInt(0)),
  materialCents: cents('material_cents').notNull().default(BigInt(0)),
  scrapCents: cents('scrap_cents').notNull().default(BigInt(0)),
  otherCents: cents('other_cents').notNull().default(BigInt(0)),
  sharedCents: cents('shared_cents').notNull().default(BigInt(0)),
  costCents: cents('cost_cents').notNull().default(BigInt(0)),
  profitCents: cents('profit_cents').notNull().default(BigInt(0)),
  marginBp: integer('margin_bp'),
  marginBeforeSharedBp: integer('margin_before_shared_bp'),
  uph: pace('uph'),
  standardUph: pace('standard_uph'),
  productivityBp: integer('productivity_bp'),
  pctCompleteBp: integer('pct_complete_bp'),
  targetMarginBp: integer('target_margin_bp'),
  mode: text('mode'),
  costAtFinishCents: cents('cost_at_finish_cents'),
  revenueAtFinishCents: cents('revenue_at_finish_cents'),
  projectedProfitCents: cents('projected_profit_cents'),
  projectedMarginBp: integer('projected_margin_bp'),
  projectedLaborHours: numeric('projected_labor_hours', { precision: 12, scale: 2 }),
  projectedFinishDate: date('projected_finish_date'),
  paceUph: pace('pace_uph'),
  paceWeightBp: integer('pace_weight_bp'),
  confidence: text('confidence'),
  riskStatus: text('risk_status'),
  riskReasons: jsonb('risk_reasons').$type<unknown[]>().notNull().default([]),
  needs: jsonb('needs').$type<Record<string, unknown>>().notNull().default({}),
  firstEntryDate: date('first_entry_date'),
  lastEntryDate: date('last_entry_date'),
  entryCount: integer('entry_count').notNull().default(0),
  computedAt: tstz('computed_at').notNull().defaultNow(),
});
