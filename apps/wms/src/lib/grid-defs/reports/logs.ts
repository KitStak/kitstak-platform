const fromTo = (stem: string, label: string, extra: Partial<ReportColumn> = {}): ReportColumn[] => [
  col(`from${stem}`, `From ${label}`, { width: 140, ...extra }),
  col(`to${stem}`, `To ${label}`, { width: 140, ...extra }),
];

