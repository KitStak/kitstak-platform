/** Outbound: shipment orders, order lines, line shortages. */
import { index, integer, doublePrecision, pgTable, text, uniqueIndex } from 'drizzle-orm/pg-core';
import type { AddressValue } from '../../../lib/domain-types';
import {
  ADDRESS_TYPES,
  ADDRESS_VERIFICATION_STATUSES,
  BILLING_PARTY_TYPES,
  EXPORT_REASONS,
  ORDER_CHANNELS,
  ORDER_TYPES,
  PRIORITIES,
  SHORT_STATUSES,
  SHORTAGE_REASONS,
  SO_STATUSES,
  TAX_TYPES,
  WORKFLOW_BLOCK_STATES,
} from '../../../lib/enums';
import { bool, customFields, json, pk, stamps } from '../columns';
import { products } from './catalog';
import { clients, customers, warehouses } from './org';

export const shipmentOrders = pgTable(
  'shipment_orders',
  {
    id: pk(),
    code: text('code').notNull(),
    warehouseId: text('warehouse_id')
      .notNull()
      .references(() => warehouses.id),
    clientId: text('client_id')
      .notNull()
      .references(() => clients.id),
    channel: text('channel', { enum: ORDER_CHANNELS }).notNull(),
    storeName: text('store_name'),
    storeOrderNumber: text('store_order_number'),
    customerName: text('customer_name').notNull(),
    customerEmail: text('customer_email').notNull(),
    shipAddress: text('ship_address').notNull(),
    shipCity: text('ship_city').notNull(),
    shipState: text('ship_state').notNull(),
    shipZip: text('ship_zip').notNull(),
    shipCountry: text('ship_country').notNull().default('United States'),
    status: text('status', { enum: SO_STATUSES }).notNull(),
    orderType: text('order_type', { enum: ORDER_TYPES }).notNull().default('D2C'),
    priority: text('priority', { enum: PRIORITIES }).notNull().default('None'),
    carrier: text('carrier'),
    shippingService: text('shipping_service'),
    trackingNumber: text('tracking_number'),
    totalQuantity: integer('total_quantity').notNull(),
    totalWeightOz: doublePrecision('total_weight_oz').notNull(),
    salesPrice: doublePrecision('sales_price').notNull(),
    jobId: text('job_id'),
    orderDate: text('order_date').notNull(),
    expectedShipDate: text('expected_ship_date'),
    shippedAt: text('shipped_at'),
    deliveredAt: text('delivered_at'),
    note: text('note'),
    orderTypeId: text('order_type_id'), // lookup so_type
    priorityRank: integer('priority_rank').notNull().default(0),
    customerId: text('customer_id').references(() => customers.id),
    customerFirstName: text('customer_first_name'),
    customerLastName: text('customer_last_name'),
    customerPhone: text('customer_phone'),
    companyName: text('company_name'),
    shipAddress2: text('ship_address2'),
    addressType: text('address_type', { enum: ADDRESS_TYPES }),
    skipAddressVerification: bool('skip_address_verification').notNull().default(false),
    addressVerificationStatus: text('address_verification_status', { enum: ADDRESS_VERIFICATION_STATUSES })
      .notNull()
      .default('Unverified'),
    addressVerificationNotes: json<string[]>('address_verification_notes'),
    taxType: text('tax_type', { enum: TAX_TYPES }),
    taxId: text('tax_id'),
    useShipAsBilling: bool('use_ship_as_billing').notNull().default(true),
    billingAddress: json<AddressValue>('billing_address'),
    expectedDeliveryDate: text('expected_delivery_date'),
    carrierExpectedDeliveryDate: text('carrier_expected_delivery_date'),
    scheduledPickupDate: text('scheduled_pickup_date'),
    scheduledShipmentDate: text('scheduled_shipment_date'),
    actualPickupDate: text('actual_pickup_date'),
    cancelledAt: text('cancelled_at'),
    cancelReasonId: text('cancel_reason_id'),
    carrierConnectionId: text('carrier_connection_id'),
    carrierServiceId: text('carrier_service_id'),
    rateShoppingPresetId: text('rate_shopping_preset_id'),
    shippingChargesBillingType: text('shipping_charges_billing_type', { enum: BILLING_PARTY_TYPES }),
    taxDutiesBillingType: text('tax_duties_billing_type', { enum: BILLING_PARTY_TYPES }),
    shippingAccountNumber: text('shipping_account_number'),
    taxDutiesAccountNumber: text('tax_duties_account_number'),
    packingInstructions: text('packing_instructions'),
    shipmentPackageId: text('shipment_package_id'),
    totalShippingCost: doublePrecision('total_shipping_cost').notNull().default(0),
    rate: doublePrecision('rate').notNull().default(0),
    discount: doublePrecision('discount').notNull().default(0),
    reasonForExport: text('reason_for_export', { enum: EXPORT_REASONS }),
    returnAddressId: text('return_address_id'),
    returnCarrierServiceId: text('return_carrier_service_id'),
    returnShippingCost: doublePrecision('return_shipping_cost'),
    returnTrackingNumbers: json<string[]>('return_tracking_numbers'),
    trackingNumbers: json<string[]>('tracking_numbers'),
    extraNote1: text('extra_note1'),
    extraNote2: text('extra_note2'),
    extraNote3: text('extra_note3'),
    extraNote4: text('extra_note4'),
    extraNote5: text('extra_note5'),
    clientReferenceCode: text('client_reference_code'),
    fraud: text('fraud'),
    packingWarningTypeId: text('packing_warning_type_id'),
    isGift: bool('is_gift').notNull().default(false),
    giftNote: text('gift_note'),
    orderCodeGroupingRef: text('order_code_grouping_ref'),
    retailerId: text('retailer_id'),
    bol: text('bol'),
    pro: text('pro'),
    retailerPo: text('retailer_po'),
    dept: text('dept'),
    markFor: text('mark_for'),
    retailerCustomerAccount: text('retailer_customer_account'),
    isUccLabelGenerated: bool('is_ucc_label_generated').notNull().default(false),
    isBackOrder: bool('is_back_order').notNull().default(false),
    masterOrderId: text('master_order_id'),
    mergedIntoOrderId: text('merged_into_order_id'),
    isMerged: bool('is_merged').notNull().default(false),
    pickShortStatus: text('pick_short_status', { enum: SHORT_STATUSES }).notNull().default('None'),
    packShortStatus: text('pack_short_status', { enum: SHORT_STATUSES }).notNull().default('None'),
    pickListPrinted: bool('pick_list_printed').notNull().default(false),
    isAutoShip: bool('is_auto_ship').notNull().default(false),
    isPrime: bool('is_prime').notNull().default(false),
    channelConnectionId: text('channel_connection_id'),
    channelPaymentStatus: text('channel_payment_status'),
    requestedShippingOption: text('requested_shipping_option'),
    workflowBlocked: text('workflow_blocked', { enum: WORKFLOW_BLOCK_STATES }).notNull().default('None'),
    deletedAt: text('deleted_at'),
    ...customFields(),
    ...stamps(),
  },
  (t) => [
    uniqueIndex('orders_code_idx').on(t.code),
    index('orders_status_idx').on(t.status),
    index('orders_client_idx').on(t.clientId),
    index('orders_date_idx').on(t.orderDate),
    index('orders_wh_status_idx').on(t.warehouseId, t.status),
    index('orders_store_number_idx').on(t.storeOrderNumber),
    index('orders_job_idx').on(t.jobId),
  ],
);

export const orderLines = pgTable(
  'order_lines',
  {
    id: pk(),
    orderId: text('order_id')
      .notNull()
      .references(() => shipmentOrders.id),
    productId: text('product_id')
      .notNull()
      .references(() => products.id),
    quantity: integer('quantity').notNull(),
    pickedQuantity: integer('picked_quantity').notNull().default(0),
    packedQuantity: integer('packed_quantity').notNull().default(0),
    unitPrice: doublePrecision('unit_price').notNull(),
    packType: text('pack_type').notNull().default('Each'),
    uomRatio: integer('uom_ratio').notNull().default(1),
    allocatedQuantity: integer('allocated_quantity').notNull().default(0),
    cancelledQuantity: integer('cancelled_quantity').notNull().default(0),
    sortedQuantity: integer('sorted_quantity').notNull().default(0),
    shippedQuantity: integer('shipped_quantity').notNull().default(0),
    loadedQuantity: integer('loaded_quantity').notNull().default(0),
    lotNumber: text('lot_number'),
    expiryDate: text('expiry_date'),
    productionDate: text('production_date'),
    damageReason: text('damage_reason'),
    pinnedLocationId: text('pinned_location_id'),
    pinnedLpId: text('pinned_lp_id'),
    lineNote1: text('line_note1'),
    lineNote2: text('line_note2'),
    lineNote3: text('line_note3'),
    kitProductId: text('kit_product_id'),
    originalOrderCode: text('original_order_code'),
    storeUpdateNotes: text('store_update_notes'),
    isStoreUpdated: bool('is_store_updated').notNull().default(false),
    ...stamps(),
  },
  (t) => [index('order_lines_order_idx').on(t.orderId), index('order_lines_product_idx').on(t.productId)],
);

export const orderLineShortages = pgTable(
  'order_line_shortages',
  {
    id: pk(),
    orderId: text('order_id').notNull(),
    orderLineId: text('order_line_id').notNull(),
    reason: text('reason', { enum: SHORTAGE_REASONS }).notNull(),
    missingTriggered: bool('missing_triggered').notNull().default(false),
    shortageQty: integer('shortage_qty').notNull(),
    freeQty: integer('free_qty').notNull(),
    damagedQty: integer('damaged_qty').notNull(),
    onHandQty: integer('on_hand_qty').notNull(),
    lastTrialAt: text('last_trial_at').notNull(),
    resolvedAt: text('resolved_at'),
  },
  (t) => [uniqueIndex('ols_line_idx').on(t.orderLineId), index('ols_order_idx').on(t.orderId)],
);
