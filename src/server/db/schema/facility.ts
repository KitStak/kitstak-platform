/** Facility: locations, capacities, LP types, license plates, mobile carts, shipment packages. */
import { index, integer, primaryKey, real, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";
import {
  ABC_CODES,
  AREA_TYPES,
  CAPACITY_TYPES,
  LEGACY_LOCATION_ROLES,
  LOCATION_TYPES,
  LP_STATUSES,
  MOBILE_CART_STATUSES,
  PACKAGE_REDUCTION_RULES,
} from "../../../lib/enums";
import { bool, customFields, pk, stamps } from "../columns";
import { products } from "./catalog";
import { clients, warehouses } from "./org";

/** Existing `type` is kept as the legacy role; `locationType` / `areaType` are authoritative. */
export const locations = sqliteTable("locations", {
  id: pk(),
  warehouseId: text("warehouse_id").notNull().references(() => warehouses.id),
  code: text("code").notNull(),
  zone: text("zone").notNull(),
  aisle: text("aisle").notNull(),
  bay: text("bay").notNull(),
  level: text("level").notNull(),
  type: text("type", { enum: LEGACY_LOCATION_ROLES }).notNull(),
  capacityUnits: integer("capacity_units").notNull(),
  isActive: bool("is_active").notNull().default(true),
  barcode: text("barcode"),
  displayMember: text("display_member"),
  locationGroupId: text("location_group_id"), // lookup_values (warehouse-scoped)
  locationZoneId: text("location_zone_id"),
  locationType: text("location_type", { enum: LOCATION_TYPES }),
  areaType: text("area_type", { enum: AREA_TYPES }),
  replenishmentType: text("replenishment_type", { enum: ["Source", "Target"] }),
  walkingPathPriority: integer("walking_path_priority").notNull().default(0),
  capacityType: text("capacity_type", { enum: CAPACITY_TYPES }).notNull().default("None"),
  maxCapacityQty: integer("max_capacity_qty").notNull().default(0),
  maxSkuQty: integer("max_sku_qty"),
  mezzanine: text("mezzanine"),
  rack: text("rack"),
  column: integer("column").notNull().default(0),
  position: text("position"),
  dimensionUnit: text("dimension_unit").notNull().default("Inch"),
  height: real("height").notNull().default(0),
  width: real("width").notNull().default(0),
  length: real("length").notNull().default(0),
  volumeUnit: text("volume_unit").notNull().default("Cubic Inch"),
  volume: real("volume").notNull().default(0),
  abcCode: text("abc_code", { enum: ABC_CODES }).notNull().default("None"),
  singleClient: bool("single_client").notNull().default(false),
  isLocked: bool("is_locked").notNull().default(false),
  dedicatedClientId: text("dedicated_client_id").references(() => clients.id),
  printApplyOnPacking: bool("print_apply_on_packing").notNull().default(false),
  colorCode: text("color_code"),
  preventAllocation: bool("prevent_allocation").notNull().default(false),
  preventInventorySync: bool("prevent_inventory_sync").notNull().default(false),
  onlyOneLot: bool("only_one_lot").notNull().default(false),
  onlyDamaged: bool("only_damaged").notNull().default(false),
  onlyOneExpiry: bool("only_one_expiry").notNull().default(false),
  onlyOneSku: bool("only_one_sku").notNull().default(false),
  onlyOneLp: bool("only_one_lp").notNull().default(false),
  onlyOneProductionDate: bool("only_one_production_date").notNull().default(false),
  autoRemoveLpAfterReplenishment: bool("auto_remove_lp_after_replenishment").notNull().default(false),
  autoRemoveLpAfterTransfer: bool("auto_remove_lp_after_transfer").notNull().default(false),
  ...customFields(),
  ...stamps(),
}, (t) => [
  uniqueIndex("locations_code_idx").on(t.warehouseId, t.code),
  index("locations_barcode_idx").on(t.barcode),
  index("locations_area_idx").on(t.warehouseId, t.areaType),
]);

export const locationProductCapacity = sqliteTable("location_product_capacity", {
  id: pk(),
  locationId: text("location_id").notNull().references(() => locations.id, { onDelete: "cascade" }),
  clientId: text("client_id").notNull().references(() => clients.id),
  productId: text("product_id").notNull().references(() => products.id),
  packType: text("pack_type").notNull(),
  minQty: integer("min_qty").notNull().default(0),
  maxQty: integer("max_qty").notNull().default(0),
}, (t) => [uniqueIndex("lpc_idx").on(t.locationId, t.productId, t.packType)]);

